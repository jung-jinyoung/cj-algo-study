/*
   문제 유형: 동적 계획법(DP)으로 이전 두 계단의 경우의 수를 더해 정상에 도달하는 방법의 수 계산
   문제7 : <LeetCode> - 70. Climbing Stairs
   난이도: Easy
*/

/*
   전략

   1. 한 번에 1칸 또는 2칸씩 이동해 n번째 계단에 도달하는 방법의 수를 구한다.
   -> n = 올라가야 하는 전체 계단 수
   -> 한 번에 이동 가능한 계단 수 = 1칸 또는 2칸
   2. 동적 계획법(DP)을 사용해 이전에 계산한 경우의 수를 재사용한다.
   -> DP = 작은 문제의 결과를 이용해 큰 문제의 결과 계산
   3. n번째 계단에 도달하는 마지막 이동은 1칸 또는 2칸이다.
   -> 1칸 이동 = n-1번째 계단에서 도착
   -> 2칸 이동 = n-2번째 계단에서 도착
   4. 따라서 n번째 계단에 도달하는 경우의 수는 이전 두 계단의 경우의 수를 더한 값이다.
   -> dp[n] = dp[n-1] + dp[n-2]
   5. 계단이 1칸이면 올라가는 방법은 1가지이다.
   -> 1칸
   6. 계단이 2칸이면 올라가는 방법은 2가지이다.
   -> 1칸 + 1칸
   -> 2칸
   7. n이 2 이하이면 n을 바로 반환한다.
   8. 이전 두 계단의 경우의 수를 저장할 변수를 초기화한다.
   -> twoBefore = 1번째 계단의 경우의 수
   -> oneBefore = 2번째 계단의 경우의 수
   9. 3번째 계단부터 n번째 계단까지 반복하면서 경우의 수를 계산한다.
   10. 현재 계단의 경우의 수는 이전 두 계단의 경우의 수를 더해 계산한다.
   -> current = twoBefore + oneBefore
   11. 다음 계단을 계산하기 위해 이전 두 계단의 값을 갱신한다.
   -> twoBefore = oneBefore
   -> oneBefore = current
   12. 마지막까지 계산한 n번째 계단의 경우의 수를 반환한다.
*/

class Solution {
    public int climbStairs(int n) {
        // 계단이 1칸 또는 2칸이면 해당 경우의 수 반환
        if (n <= 2) {
            return n;
        }
        // 1번째 계단에 도달하는 경우의 수
        int twoBefore = 1;
        // 2번째 계단에 도달하는 경우의 수
        int oneBefore = 2;
        // 3번째 계단부터 n번째 계단까지 계산
        for (int i = 3; i <= n; i++) {
            // 현재 계단의 경우의 수 = 이전 두 계단의 경우의 수 합
            int current = twoBefore + oneBefore;
            // 다음 계산을 위해 이전 두 계단의 값 갱신
            twoBefore = oneBefore;
            oneBefore = current;
        }
        // n번째 계단에 도달하는 전체 경우의 수 반환
        return oneBefore;
    }
}