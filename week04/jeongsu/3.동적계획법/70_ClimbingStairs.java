/*
 풀이 전략
 - dp[i]를 i번째 계단에 도착하는 방법의 수로 정의한다.
 - 마지막 이동은 i-1번째에서 1칸 올라오거나,
   i-2번째에서 2칸 올라오는 두 경우로 나뉜다.
 - 두 경우는 마지막 이동이 서로 다르므로 방법 수를 더한다.
   점화식은 dp[i] = dp[i-1] + dp[i-2]이다.
 - dp[1] = 1, dp[2] = 2로 설정하고 작은 계단부터 순서대로 채운다.
 - n이 1이면 dp[2] 접근을 피하도록 먼저 1을 반환한다.
 - 최종적으로 dp[n]을 반환한다.

 시간복잡도: O(N)
 - 3번째부터 N번째 계단까지 한 번씩 계산한다.
 - 각 상태는 배열 조회와 덧셈만 수행하므로 O(1)이 걸린다.
 */
class Solution {
    public int climbStairs(int n) {
        //n이 1이면 dp[2]에 접근하지 않도록 먼저 반환
        if(n==1){
            return 1;
        }
        int [] dp = new int[n+1];

        //초기값
        dp[1] = 1;
        dp[2] = 2;

        for(int i = 3;i<=n;i++){
            dp[i] = dp[i-1]+dp[i-2];
        }
        return dp[n];
    }
}